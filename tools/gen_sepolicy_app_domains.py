# Repeat the stock vendor policy's app-domain rules for the app domains
# Android 17 split off.
#
# Android 17 runs platform-signed apps and priv-apps that target SDK 36 or
# lower in platform_app_36 / priv_app_36, and other apps that target SDK 34-36
# in untrusted_app_34 (system/sepolicy private/seapp_contexts). For a vendor
# policy at board API 202504 the platform compat mapping folds the new domains
# into platform_app / priv_app / untrusted_app
# (system/sepolicy private/compat/202504/202504.cil), but this vendor policy is
# built at 202604, where no mapping applies. mtk_proprietary.te names only the
# old domains, so this emits each such rule again for the split-off domain.
#
# Run after regenerating sepolicy/vendor_mtk_prebuilt/mtk_proprietary.te.

import os
import re

DEVICE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POLICY_DIR = os.path.join(DEVICE_DIR, 'sepolicy', 'vendor_mtk_prebuilt')
SOURCE = os.path.join(POLICY_DIR, 'mtk_proprietary.te')
OUTPUT = os.path.join(POLICY_DIR, 'tb375fc_app_domains.te')

# Old domain -> domain split off from it, as in 202504.cil.
SPLITS = {
    'platform_app': 'platform_app_36',
    'priv_app': 'priv_app_36',
    'untrusted_app': 'untrusted_app_34',
}
TOKEN = re.compile(r'(?<![\w])(' + '|'.join(SPLITS) + r')(?![\w])')

HEADER = """\
# GENERATED by tools/gen_sepolicy_app_domains.py from mtk_proprietary.te; do not
# edit.
#
# Android 17 runs apps targeting older SDKs in platform_app_36, priv_app_36 and
# untrusted_app_34. The stock vendor policy predates that split, and the 202504
# compat mapping that covers it does not apply to this 202604 vendor policy, so
# every stock platform_app / priv_app / untrusted_app rule is repeated here for
# the split-off domain. Lives in vendor_mtk_prebuilt so it compiles after the
# vendor types it names.

"""


def main():
    with open(SOURCE) as f:
        lines = f.read().splitlines()

    rules = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        if len(TOKEN.findall(stripped)) > 1:
            raise SystemExit(f'more than one app domain in rule: {stripped}')
        if TOKEN.search(stripped):
            rules.append(TOKEN.sub(lambda m: SPLITS[m.group(1)], stripped))

    with open(OUTPUT, 'w') as f:
        f.write(HEADER)
        f.write('\n'.join(rules))
        f.write('\n')


if __name__ == '__main__':
    main()
